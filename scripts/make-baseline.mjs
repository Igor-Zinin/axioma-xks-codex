#!/usr/bin/env node
/**
 * Generates the reference baseline from the benchmark and the response contract.
 *
 * The baseline is a protocol fixture, not a model result: a hand-written perfect
 * submission proving the evaluator and the result shape work before any provider is
 * measured. It used to be maintained by hand, which is how it came to state the
 * response shape a second time — and to state it differently from the prompt that
 * evaluated models are actually given. Generating it removes the second list.
 *
 * Run: node scripts/make-baseline.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const protocol = JSON.parse(fs.readFileSync(path.join(root, "docs/data/chess-benchmark-v0.1.json"), "utf8"));
const contract = JSON.parse(fs.readFileSync(path.join(root, "docs/data/chess-response-contract-v0.1.json"), "utf8"));

function perfectResponse(task) {
  // Every fixture carries every contract field; inapplicable ones are null, exactly
  // as the evaluated model is instructed to answer.
  const r = { move: null, legal: null, state_fen: null, explanation: null, completed: true };
  if (task.family === "legality") { r.move = task.expected.move; r.legal = task.expected.legal; }
  if (task.family === "tactics") { r.move = task.expected.best_move; r.legal = true; }
  if (task.family === "state_tracking") { r.state_fen = task.expected_fen; r.move = task.moves[0]; r.legal = true; }
  if (task.family === "interactive_play") { r.move = task.expected_moves[0]; r.state_fen = task.expected_fen; r.legal = true; }
  if (task.family === "explanation") {
    const [square, timing] = task.required_concepts;
    r.explanation = `The capture on ${square} is available only on the ${timing} move.`;
  }
  const missing = (contract.families[task.family]?.required || []).filter((f) => r[f] === null);
  if (missing.length) throw new Error(`baseline cannot satisfy contract for ${task.id}: ${missing.join(", ")}`);
  return r;
}

const responses = {};
for (const task of protocol.tasks) responses[task.id] = perfectResponse(task);

const baseline = {
  game: protocol.game,
  protocol: protocol.protocol,
  model: "reference-baseline",
  provider: "deterministic fixture / no provider",
  response_contract: contract.contract,
  date: "2026-08-11T00:00:00Z",
  note: "Protocol control fixture, not a model result. Generated by scripts/make-baseline.mjs.",
  trials: [1, 2, 3].map(() => ({ responses }))
};

const out = path.join(root, "docs/data/chess-baseline-v0.1.json");
fs.writeFileSync(out, `${JSON.stringify(baseline, null, 2)}\n`);
console.log(`wrote ${path.relative(root, out)} — ${protocol.tasks.length} fixtures x ${baseline.trials.length} trials`);
